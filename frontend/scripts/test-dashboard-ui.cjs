require('./register-typescript.cjs');
const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');
const dom = new JSDOM('<!doctype html><html lang="en"><head><title>Dashboard interaction test</title></head><body><main><div id="root"></div></main></body></html>', { url: 'http://localhost/platform/dashboard' });
global.self = dom.window; global.window = dom.window; global.document = dom.window.document; global.navigator = dom.window.navigator;
global.HTMLElement = dom.window.HTMLElement; global.Element = dom.window.Element; global.Node = dom.window.Node;
global.IS_REACT_ACT_ENVIRONMENT = true;
const React = require('react');
const { createRoot } = require('react-dom/client');
const { DashboardTabs } = require('../components/platform/dashboard-tabs.tsx');
const { DashboardAssets } = require('../components/platform/dashboard-assets.tsx');
const { assets } = require('../lib/demo-data.ts');
const root = createRoot(document.getElementById('root'));
(async () => {
  const panels = Object.fromEntries(['overview', 'analytics', 'assets', 'evidence', 'demo'].map(id => [id, React.createElement('p', null, id + ' content')]));
  await React.act(async () => root.render(React.createElement(DashboardTabs, { panels })));
  const tabs = [...document.querySelectorAll('[role="tab"]')];
  assert.equal(tabs.length, 5);
  assert.equal(tabs[0].getAttribute('aria-selected'), 'true');
  await React.act(async () => tabs[0].dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true })));
  assert.equal(tabs[1].getAttribute('aria-selected'), 'true');
  assert.equal(document.activeElement, tabs[1]);
  assert.equal(document.querySelectorAll('[role="tabpanel"]:not([hidden])').length, 1);
  assert.match(document.getElementById('panel-analytics').textContent, /analytics content/);
  await React.act(async () => tabs[1].dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: 'End', bubbles: true })));
  assert.equal(document.activeElement, tabs[4]);
  await React.act(async () => tabs[0].click());
  assert.equal(tabs[0].getAttribute('aria-selected'), 'true');
  const accessibility = await require('axe-core').run(document, { rules: { 'color-contrast': { enabled: false } } });
  assert.deepEqual(accessibility.violations.map(item => item.id), []);
  console.log('PASS dashboard tabs: click, keyboard selection, focus, panel isolation, accessible semantics');
  await React.act(async () => root.render(React.createElement(DashboardAssets)));
  assert.equal(document.querySelectorAll('tbody tr').length, assets.length);
  const select = document.querySelector('select');
  await React.act(async () => { select.value = 'At Risk'; select.dispatchEvent(new dom.window.Event('change', { bubbles: true })); });
  const matching = assets.filter(asset => asset.complianceStatus === 'At Risk');
  assert.equal(document.querySelectorAll('tbody tr').length, matching.length);
  assert.equal(document.querySelector('tbody strong').textContent, 'EP501');
  await React.act(async () => document.querySelector('thead button').click());
  assert.equal(document.querySelector('tbody strong').textContent, 'HX401');
  assert.equal(document.querySelector('th[aria-sort]').getAttribute('aria-sort'), 'ascending');
  const input = document.querySelector('input');
  await React.act(async () => {
    Object.getOwnPropertyDescriptor(dom.window.HTMLInputElement.prototype, 'value').set.call(input, 'unmatched');
    input.dispatchEvent(new dom.window.Event('input', { bubbles: true }));
  });
  assert.equal(document.querySelectorAll('tbody tr').length, 0);
  assert.match(document.querySelector('[role="status"]').textContent, /No demo assets match/);
  assert.equal(assets.length, 6, 'Source assets must remain unchanged');
  console.log('PASS asset watchlist: existing data, status filter, sort, search, empty state; no API/network calls');
  await React.act(async () => root.unmount()); dom.window.close();
})().catch(error => { console.error(error); process.exitCode = 1; dom.window.close(); });
